// export_gen.cpp -- JSON Export + C++ Header Generator
// *outputs machine-readable artifacts from the dump, ready for any downstream tool*
#include "dumper.h"
#include <sstream>
#include <iomanip>
#include <ctime>
#include <chrono>

static std::string JsonEscape(const std::string& s) {
    std::string out;
    for (char c : s) {
        switch(c) {
            case '"':  out += "\\\""; break;
            case '\\': out += "\\\\"; break;
            case '\n': out += "\\n";  break;
            case '\r': out += "\\r";  break;
            case '\t': out += "\\t";  break;
            default:   out += c;      break;
        }
    }
    return out;
}

static std::string WStr(const std::wstring& w) {
    if (w.empty()) return {};
    int sz = WideCharToMultiByte(CP_UTF8, 0, w.c_str(), -1, nullptr, 0, nullptr, nullptr);
    std::string s(sz-1, 0);
    WideCharToMultiByte(CP_UTF8, 0, w.c_str(), -1, &s[0], sz, nullptr, nullptr);
    return s;
}

bool WriteJSON(const DumpResult& result, const std::wstring& outputPath) {
    auto now = std::chrono::system_clock::now();
    std::time_t t = std::chrono::system_clock::to_time_t(now);
    char timeBuf[64] = {};
    ctime_s(timeBuf, sizeof(timeBuf), &t);
    std::string ts = timeBuf;
    if (!ts.empty() && ts.back() == '\n') ts.pop_back();

    std::ostringstream j;
    j << "{\r\n";
    j << "  \"game\": \""   << JsonEscape(WStr(result.processName)) << "\",\r\n";
    j << "  \"pid\": "      << result.pid << ",\r\n";
    j << "  \"engine\": \"" << JsonEscape(EngineTypeName(result.engine)) << "\",\r\n";
    j << "  \"timestamp\": \"" << JsonEscape(ts) << "\",\r\n";

    // Modules
    j << "  \"modules\": [\r\n";
    for (size_t i = 0; i < result.modules.size(); i++) {
        auto& m = result.modules[i];
        std::ostringstream ba;
        ba << "0x" << std::hex << std::uppercase << m.base;
        j << "    { \"name\": \"" << JsonEscape(WStr(m.name)) << "\","
          << " \"base\": \"" << ba.str() << "\","
          << " \"size\": " << m.size << " }";
        if (i + 1 < result.modules.size()) j << ",";
        j << "\r\n";
    }
    j << "  ],\r\n";

    // Offsets (patterns)
    j << "  \"offsets\": {\r\n";
    bool first = true;
    for (auto& p : result.patterns) {
        // Skip string xrefs from the main offsets block
        if (p.label.find("xref_") == 0) continue;
        if (!first) j << ",\r\n";
        std::ostringstream addr;
        addr << "0x" << std::hex << std::uppercase << p.address;
        static const char* CONF_STR[] = { "DEAD", "LOW", "MEDIUM", "HIGH" };
        j << "    \"" << JsonEscape(p.label) << "\": { "
          << "\"address\": \"" << addr.str() << "\", "
          << "\"offset\": " << p.offset << ", "
          << "\"module\": \"" << JsonEscape(p.moduleName) << "\", "
          << "\"confidence\": \"" << CONF_STR[p.confidence & 3] << "\" }";
        first = false;
    }
    j << "\r\n  },\r\n";

    // PE Sections
    j << "  \"sections\": [\r\n";
    for (size_t i = 0; i < result.sections.size(); i++) {
        auto& s = result.sections[i];
        j << "    { \"name\": \"" << s.name << "\","
          << " \"rva\": " << s.rva << ","
          << " \"virtualSize\": " << s.virtualSize << " }";
        if (i + 1 < result.sections.size()) j << ",";
        j << "\r\n";
    }
    j << "  ]\r\n";
    j << "}\r\n";

    std::string text = j.str();
    FILE* fp = nullptr;
    _wfopen_s(&fp, outputPath.c_str(), L"wb");
    if (!fp) return false;
    fwrite(text.c_str(), 1, text.size(), fp);
    fclose(fp);
    return true;
}

bool WriteCppHeader(const DumpResult& result, const std::wstring& outputPath) {
    auto now = std::chrono::system_clock::now();
    std::time_t t = std::chrono::system_clock::to_time_t(now);
    char timeBuf[64] = {};
    ctime_s(timeBuf, sizeof(timeBuf), &t);
    std::string ts = timeBuf;
    if (!ts.empty() && ts.back() == '\n') ts.pop_back();

    std::string pn = WStr(result.processName);
    std::string en = EngineTypeName(result.engine);

    std::ostringstream out;
    out << "// AUTO-GENERATED by ProcessDumper v4.0\r\n";
    out << "// Game  : " << pn << "\r\n";
    out << "// Engine: " << en << "\r\n";
    out << "// Time  : " << ts << "\r\n";
    out << "// DO NOT EDIT -- regenerate with ProcessDumper\r\n";
    out << "#pragma once\r\n\r\n";
    out << "namespace offsets {\r\n\r\n";

    // Group by module
    std::string lastMod = "";
    for (auto& p : result.patterns) {
        if (p.label.find("xref_") == 0) continue; // skip string xrefs
        if (p.moduleName != lastMod) {
            if (!lastMod.empty()) out << "\r\n";
            out << "    // --- " << p.moduleName << " ---\r\n";
            lastMod = p.moduleName;
        }
        static const char* CONF_STR[] = { "DEAD", "LOW", "MEDIUM", "HIGH" };
        out << "    constexpr uintptr_t " << p.label
            << " = 0x" << std::hex << std::uppercase << p.address << std::dec
            << "; // [" << CONF_STR[p.confidence & 3] << "]";
        if (!p.notes.empty()) out << " " << p.notes;
        out << "\r\n";
    }

    out << "\r\n} // namespace offsets\r\n\r\n";

    // Also emit C# version
    out << "#if 0  // C# version\r\n";
    out << "public static class Offsets {\r\n";
    for (auto& p : result.patterns) {
        if (p.label.find("xref_") == 0) continue;
        out << "    public const long " << p.label
            << " = 0x" << std::hex << std::uppercase << p.address << std::dec << ";\r\n";
    }
    out << "}\r\n#endif\r\n";

    std::string text = out.str();
    FILE* fp = nullptr;
    _wfopen_s(&fp, outputPath.c_str(), L"wb");
    if (!fp) return false;
    fwrite(text.c_str(), 1, text.size(), fp);
    fclose(fp);
    return true;
}
